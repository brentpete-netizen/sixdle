// Filters the word-list npm package (274k common English words, no
// proper nouns) down to 6-letter entries, and writes them out as a
// browser-loadable array. Run this again if the source list changes.
const fs = require("fs");
const path = require("path");
const wordListPath = require("word-list").default;
const { WORDS: ANSWERS } = require("./words.js");

const raw = fs.readFileSync(wordListPath, "utf8");
const all = raw.split("\n").map((w) => w.trim()).filter(Boolean);

const sixLetter = all.filter((w) => /^[a-z]{6}$/.test(w));
const dictionary = Array.from(new Set(sixLetter)).sort();

// Every possible answer must also be accepted as a valid guess.
const missing = ANSWERS.filter((w) => !dictionary.includes(w));
const finalDictionary = Array.from(new Set([...dictionary, ...missing])).sort();

const out = `// Auto-generated by build-dictionary.js — do not edit by hand.
// Source: word-list npm package, filtered to 6-letter words.
const DICTIONARY = ${JSON.stringify(finalDictionary)};
`;

fs.writeFileSync(path.join(__dirname, "dictionary.js"), out);

console.log(`Wrote ${finalDictionary.length} six-letter words to dictionary.js`);
if (missing.length) {
  console.log(`Added ${missing.length} curated answers missing from source list:`, missing);
}
